// Flattened, deduped-by-id list for the admin dashboard's management grid.
// Each entry remembers every place it appears (gallery category and/or
// service ids) so a single hide/category action can represent the whole
// photo/video, not just one placement of it.
export function flattenStaticMedia() {
  const map = new Map();

  for (const p of galleryPhotos) {
    map.set(p.id, {
      id: p.id,
      kind: "photo",
      thumb: p.src,
      galleryCategory: p.category,
      serviceIds: [],
    });
  }
  for (const v of galleryVideos) {
    map.set(v.id, {
      id: v.id,
      kind: "video",
      thumb: v.poster,
      galleryCategory: v.category,
      serviceIds: [],
    });
  }
  for (const [serviceId, items] of Object.entries(serviceMedia)) {
    for (const item of items) {
      const existing = map.get(item.id);
      if (existing) {
        existing.serviceIds.push(serviceId);
      } else {
        map.set(item.id, {
          id: item.id,
          kind: item.type,
          thumb: item.type === "video" ? item.poster : item.src,
          galleryCategory: null,
          serviceIds: [serviceId],
        });
      }
    }
  }

  return [...map.values()];
}
